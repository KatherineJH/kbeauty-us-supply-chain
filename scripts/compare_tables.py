"""Compare the regenerated result tables (reports/tables/*.csv) with the committed references.

    uv run python scripts/compare_tables.py            # CI: canonical (Linux) + cross-platform checks
    uv run python scripts/compare_tables.py --exact    # byte-identical to reports/tables (same environment)

Reproducibility levels:
- Same machine: every table is byte-identical on a rerun (run_all.py rounds floats to 12 decimals). Check a
  local rerun in the author environment with --exact.
- Canonical environment: Linux with the pinned numeric environment (src/kbeauty/numeric_env.py). Every table
  is byte-identical on any runner CPU. On Linux this script requires all 31 tables to be byte-identical to
  reports/platform/linux/ and that reference to match the SHA-256 recorded in its MANIFEST.json.
- Across operating systems, against reports/tables/ (author environment, Windows):
  * platform-invariant tables (23): numeric columns within rtol/atol (default 1e-6 / 1e-9), other columns
    exactly. A flipped discrete choice fails.
  * platform-sensitive tables (8, src/kbeauty/platform_rules.py): schema, keys, finite values, plausible
    ranges, non-ML rows within a looser tolerance, unchanged operating recommendations.

The references are the versions in git (default HEAD), so run this after scripts/run_all.py.
Exit status 1 lists every problem.
"""

import argparse
import hashlib
import io
import json
import os
import platform
import subprocess
import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from kbeauty import platform_rules  # noqa: E402
from kbeauty.platform_rules import SENSITIVE, compare_frames  # noqa: E402

TABLES = REPO / "reports" / "tables"


def committed(ref: str, rel: str) -> bytes | None:
    r = subprocess.run(["git", "show", f"{ref}:{rel}"], cwd=REPO, capture_output=True)
    return r.stdout if r.returncode == 0 else None


def tracked(ref: str, folder: str) -> set[str]:
    r = subprocess.run(["git", "ls-tree", "--name-only", f"{ref}:{folder}"], cwd=REPO, capture_output=True, text=True)
    return {n for n in r.stdout.split() if n.endswith(".csv")} if r.returncode == 0 else set()


def _cpu_model() -> str:
    info = Path("/proc/cpuinfo")
    if info.exists():
        for line in info.read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    return platform.processor()


def canonical(ref: str, current: set[str]) -> list[str]:
    """All tables byte-identical to reports/platform/linux, whose files match their MANIFEST.json hashes."""
    folder = "reports/platform/linux"
    raw = committed(ref, f"{folder}/MANIFEST.json")
    if raw is None:
        return [f"canonical  {folder}/MANIFEST.json missing in {ref}"]
    meta = json.loads(raw)
    manifest = meta["tables"]
    run_url = os.environ.get("GITHUB_RUN_ID")
    if run_url and meta.get("workflow_run") and meta["workflow_run"].rstrip("/").endswith(f"/runs/{run_url}"):
        return [f"canonical  the reference was generated by this same run ({meta['workflow_run']}); "
                "verification must run on a new runner"]
    have = tracked(ref, folder)
    out = [f"canonical  {n}: in {folder} but not regenerated" for n in sorted(have - current)]
    out += [f"canonical  {n}: regenerated but missing from {folder}" for n in sorted(current - have)]
    out += [f"canonical  {n}: listed in MANIFEST.json but not committed" for n in sorted(set(manifest) - have)]
    same = 0
    for name in sorted(have & current):
        ref_bytes = committed(ref, f"{folder}/{name}")
        if name not in manifest or hashlib.sha256(ref_bytes).hexdigest() != manifest[name]["sha256"]:
            out.append(f"canonical  {name}: committed file does not match MANIFEST.json")
        elif (TABLES / name).read_bytes() != ref_bytes:
            out.append(f"canonical  {name}: not byte-identical to {folder}")
        else:
            same += 1
    print(f"canonical  {same}/{len(current)} tables byte-identical to {folder} "
          f"(reference: {meta.get('workflow_run')}, {meta['runner']['cpu']['model']}, {meta.get('generated_at_utc')}; "
          f"this run: {os.environ.get('GITHUB_RUN_ID', 'local')}, {_cpu_model()})")
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default="HEAD", help="git revision holding the reference tables")
    ap.add_argument("--exact", action="store_true", help="require byte-identical files (same environment)")
    ap.add_argument("--rtol", type=float, default=1e-6)
    ap.add_argument("--atol", type=float, default=1e-9)
    ap.add_argument("--canonical", choices=["auto", "yes", "no"], default="auto",
                    help="require byte-identity with reports/platform/linux (auto: only on Linux)")
    args = ap.parse_args()

    current = {p.name for p in TABLES.glob("*.csv")}
    reference = tracked(args.ref, "reports/tables")
    problems = [f"{n}: missing (in {args.ref}, not regenerated)" for n in sorted(reference - current)]
    problems += [f"{n}: new table not in {args.ref}" for n in sorted(current - reference)]
    both = sorted(current & reference)

    if args.exact:
        problems += [f"{n}: not byte-identical" for n in both
                     if (TABLES / n).read_bytes() != committed(args.ref, f"reports/tables/{n}")]
        if problems:
            print(f"tables   {len(problems)} of {len(reference)} differ from {args.ref} (byte-identical):")
            print("\n".join(f"  {p}" for p in problems))
            sys.exit(1)
        print(f"tables   {len(reference)} tables match {args.ref} (byte-identical)")
        return

    invariant = [n for n in both if n not in SENSITIVE]
    for name in invariant:
        new_bytes, old_bytes = (TABLES / name).read_bytes(), committed(args.ref, f"reports/tables/{name}")
        if new_bytes != old_bytes:
            issue = compare_frames(pd.read_csv(io.BytesIO(new_bytes)), pd.read_csv(io.BytesIO(old_bytes)),
                                   args.rtol, args.atol)
            if issue:
                problems.append(f"{name}: {issue}")
    print(f"invariant  {len(invariant)} tables checked within rtol={args.rtol:g}, atol={args.atol:g}")

    missing = [n for n in SENSITIVE if n not in current or n not in reference]
    if missing:
        problems.append(f"sensitive tables missing: {missing}")
    else:
        load = lambda b: pd.read_csv(io.BytesIO(b))  # noqa: E731
        new = {n: pd.read_csv(TABLES / n) for n in SENSITIVE}
        ref = {n: load(committed(args.ref, f"reports/tables/{n}")) for n in SENSITIVE}
        found, notes = platform_rules.check_all(new, ref)
        problems += found
        print(f"sensitive  {len(SENSITIVE)} tables checked by rules (schema, keys, finite, ranges, non-ML "
              f"rtol {platform_rules.STAT_RTOL:g}, recommendations)")
        print("\n".join(f"  {n}" for n in notes))

    if args.canonical == "yes" or (args.canonical == "auto" and platform.system() == "Linux"):
        problems += canonical(args.ref, current)
    else:
        print("canonical  skipped (not Linux)")

    if problems:
        print(f"tables   {len(problems)} problems against {args.ref}:")
        print("\n".join(f"  {p}" for p in problems))
        sys.exit(1)
    print(f"tables   all {len(reference)} tables pass against {args.ref}")


if __name__ == "__main__":
    main()
